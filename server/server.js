async function initializeDatabase() {
    await pool.query("CREATE TABLE IF NOT EXISTS users (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, password TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'visitor', verified BOOLEAN NOT NULL DEFAULT FALSE, profile_image TEXT DEFAULT '', bio TEXT DEFAULT '', created_at TIMESTAMPTZ DEFAULT NOW())");
    await pool.query("CREATE TABLE IF NOT EXISTS videos (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title TEXT NOT NULL, description TEXT, category TEXT NOT NULL, video_url TEXT NOT NULL DEFAULT '', user_id BIGINT REFERENCES users(id) ON DELETE SET NULL, approved BOOLEAN NOT NULL DEFAULT FALSE, bible_reference TEXT, study_content TEXT, views_count BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ DEFAULT NOW())");
    await pool.query("CREATE TABLE IF NOT EXISTS comments (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, video_id BIGINT NOT NULL REFERENCES videos(id) ON DELETE CASCADE, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, comment TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT NOW())");
    await pool.query("CREATE TABLE IF NOT EXISTS follows (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, follower_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, followed_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, created_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(follower_id, followed_id))");
    await pool.query("CREATE TABLE IF NOT EXISTS watch_history (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, video_id BIGINT NOT NULL REFERENCES videos(id) ON DELETE CASCADE, watched_at TIMESTAMPTZ DEFAULT NOW(), UNIQUE(user_id, video_id))");
    await pool.query("CREATE TABLE IF NOT EXISTS notifications (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE, message TEXT NOT NULL, is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ DEFAULT NOW())");
    await pool.query("CREATE TABLE IF NOT EXISTS admin_profile (id INTEGER PRIMARY KEY CHECK (id = 1), name TEXT NOT NULL, profile_image TEXT DEFAULT '', bio TEXT DEFAULT '')");
    await pool.query("ALTER TABLE users ADD COLUMN IF NOT EXISTS profile_image TEXT DEFAULT ''");
    await pool.query("ALTER TABLE users ADD COLUMN IF NOT EXISTS bio TEXT DEFAULT ''");
    await pool.query("ALTER TABLE videos ADD COLUMN IF NOT EXISTS bible_reference TEXT");
    await pool.query("ALTER TABLE videos ADD COLUMN IF NOT EXISTS study_content TEXT");
    await pool.query("ALTER TABLE videos ADD COLUMN IF NOT EXISTS views_count BIGINT NOT NULL DEFAULT 0");
    await pool.query("CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_unique ON users (LOWER(email))");
    await pool.query("CREATE INDEX IF NOT EXISTS videos_approved_created_idx ON videos(approved, created_at DESC)");
    await pool.query("CREATE INDEX IF NOT EXISTS comments_video_created_idx ON comments(video_id, created_at)");
}

async function getUser(id) {
    const r = await pool.query("SELECT id, name, email, role, verified, profile_image, bio FROM users WHERE id = $1", [id]);
    return r.rows[0] || null;
}

async function authenticate(req, res, next) {
    const header = req.headers.authorization;
    if (!header || !header.startsWith("Bearer ")) return res.status(401).json({ error: "Je moet eerst inloggen." });
    try {
        req.user = jwt.verify(header.slice(7), JWT_SECRET);
        if (req.user.role !== "admin" && !(await getUser(req.user.id))) return res.status(401).json({ error: "Dit account bestaat niet meer. Maak een nieuw account aan." });
        next();
    } catch (e) {
        if (e.name === "JsonWebTokenError" || e.name === "TokenExpiredError") return res.status(401).json({ error: "Je sessie is ongeldig." });
        next(e);
    }
}

function adminOnly(req, res, next) {
    if (req.user.role !== "admin" || req.user.id !== "faithtube-main-admin") return res.status(403).json({ error: "Geen beheerderstoegang." });
    next();
}

