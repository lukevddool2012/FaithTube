        const user = r.rows[0];
        if (!user || !(await bcrypt.compare(password, user.password))) return res.status(401).json({ error: "E-mailadres of wachtwoord is onjuist." });
        const safeUser = { id: user.id, name: user.name, email: user.email, role: "visitor", verified: Boolean(user.verified) };
