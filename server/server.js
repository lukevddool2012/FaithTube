app.post("/register", async (req, res) => {
    try {
        const { name, email, password } = req.body;
        if (typeof name !== "string" || typeof email !== "string" || typeof password !== "string" || name.trim().length < 2 || name.trim().length > 60 || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim()) || password.length < 8 || password.length > 72) return res.status(400).json({ error: "Controleer je naam, e-mailadres en wachtwoord (minimaal 8 tekens)." });
        const normalized = email.trim().toLowerCase();
        const exists = await pool.query("SELECT id FROM users WHERE LOWER(email) = $1", [normalized]);
        if (exists.rowCount) return res.status(409).json({ error: "Dit e-mailadres bestaat al." });
        const hash = await bcrypt.hash(password, 12);
        const result = await pool.query("INSERT INTO users (name,email,password,role) VALUES ($1,$2,$3,'visitor') RETURNING id", [name.trim(), normalized, hash]);
        const id = result.rows[0].id;
        const token = jwt.sign({ id, name: name.trim(), email: normalized, role: "visitor", verified: false }, JWT_SECRET, { expiresIn: "30d" });
        res.status(201).json({ message: "Je account is aangemaakt!", token, userId: id });
    } catch (e) {
        console.error(e);
        res.status(e.code === "23505" ? 409 : 500).json({ error: e.code === "23505" ? "Dit e-mailadres bestaat al." : "Registreren is mislukt." });
    }
});

